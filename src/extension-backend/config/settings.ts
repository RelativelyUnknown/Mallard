/**
 * The one table of every `mallard.*` setting. It drives, from this single
 * definition:
 *
 *  - runtime validation: VS Code does NOT enforce a contributed schema on read
 *    (spike S4: out-of-range numbers, bad enums and malformed array items all
 *    reach `get()` verbatim), so every value passes through `sanitize` before
 *    anything uses it;
 *  - the defaults and ranges the rest of the extension sees;
 *  - `package.json` `contributes.configuration` (a test asserts the manifest
 *    matches this table: keys, defaults, minimum/maximum, enum, scope,
 *    description);
 *  - `docs/reference/settings.md` (generated by `scripts/gen-settings-docs.ts`).
 *
 * Pure: no `vscode` import, so tests and scripts can load it directly.
 *
 * To add a setting: add it here, add the matching property to `package.json`
 * (the manifest test says exactly what differs), then `bun run docs:settings`.
 */
import type { FlatAlertMetric, FlatAlertRule } from '../domain/contracts';
import type { ExportTarget, PaletteMode } from '../domain/types';
import { opt } from '../util/lang';

/** Where a setting may be set. Every setting declares one explicitly (the default would be `window`, which a workspace can override). */
export type SettingScope = 'application' | 'machine' | 'machine-overridable';

/** Docs-only grouping. */
export type SettingGroup = 'Budgets and alerts' | 'Dashboard' | 'Data sources' | 'GitHub billing' | 'Metric export';

type JsonSchema = Readonly<Record<string, unknown>>;

/** Handed to every `sanitize` call: where to report a dropped value, and ids already used by the target lists. */
export interface SanitizeContext {
  /** Report a value that was ignored or replaced, prefixed with the setting key. */
  report(problem: string): void;
  /** Export-target ids already taken in this read (webhook and MQTT targets share one id space). */
  readonly targetIds: Set<string>;
}

export interface SettingDef<T> {
  readonly type: 'boolean' | 'number' | 'integer' | 'string' | 'array' | 'object';
  readonly default: T;
  readonly scope: SettingScope;
  readonly description: string;
  readonly group: SettingGroup;
  /** Only read at activation: changing it prompts for a window reload. */
  readonly reload?: true;
  readonly minimum?: number;
  readonly maximum?: number;
  readonly enum?: readonly string[];
  readonly enumDescriptions?: readonly string[];
  readonly pattern?: string;
  /** JSON-schema `items` of an array setting. */
  readonly items?: JsonSchema;
  /** JSON-schema `additionalProperties` of an object setting. */
  readonly additionalProperties?: JsonSchema;
  /** Turn whatever is in the settings into a valid value; never throws. */
  readonly sanitize: (raw: unknown, ctx: SanitizeContext) => T;
}

interface Common {
  scope: SettingScope;
  description: string;
  group: SettingGroup;
  reload?: true;
}

const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);
const isNumber = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);
const isText = (v: unknown): v is string => typeof v === 'string' && v.trim() !== '';
const clamp = (n: number, min: number, max: number): number => Math.min(max, Math.max(min, n));
/** Upper bound for every money/credit amount: far past anything real, but finite for the Settings UI. */
const MAX_AMOUNT = 1_000_000;

function bool(o: Common & { default: boolean }): SettingDef<boolean> {
  return { ...o, type: 'boolean', sanitize: (raw) => (typeof raw === 'boolean' ? raw : o.default) };
}

function num(o: Common & { default: number; minimum: number; maximum: number; integer?: true }): SettingDef<number> {
  const { integer, ...rest } = o;
  return {
    ...rest,
    type: integer ? 'integer' : 'number',
    sanitize: (raw) =>
      isNumber(raw) ? clamp(integer ? Math.trunc(raw) : raw, o.minimum, o.maximum) : o.default,
  };
}

/** Free text, trimmed (a URL or path with stray whitespace is never meant). */
function text(o: Common): SettingDef<string> {
  return { ...o, type: 'string', default: '', sanitize: (raw) => (typeof raw === 'string' ? raw.trim() : '') };
}

function choice<T extends string>(o: Common & { default: T; enum: readonly T[]; enumDescriptions?: readonly string[] }): SettingDef<T> {
  return { ...o, type: 'string', sanitize: (raw) => (o.enum.includes(raw as T) ? (raw as T) : o.default) };
}

type ItemResult<T> = { value: T } | { error: string };

/**
 * An array of objects, validated one entry at a time: a bad entry (or a repeated
 * id) is dropped and reported, its siblings are kept. An absent value is the
 * default; a value that is not an array at all is reported and ignored.
 */
function list<T extends { id: string }>(
  o: Common & { items: JsonSchema; item: (raw: unknown) => ItemResult<T>; sharedIds?: true },
): SettingDef<T[]> {
  const { item, sharedIds, ...rest } = o;
  return {
    ...rest,
    type: 'array',
    default: [],
    sanitize: (raw, ctx) => {
      if (raw === undefined) return [];
      if (!Array.isArray(raw)) {
        ctx.report('expected an array; ignoring it');
        return [];
      }
      const seen = sharedIds ? ctx.targetIds : new Set<string>();
      const out: T[] = [];
      raw.forEach((entry: unknown, i) => {
        const r = item(entry);
        if ('error' in r) return ctx.report(`entry ${i + 1} ignored: ${r.error}`);
        if (seen.has(r.value.id)) return ctx.report(`entry ${i + 1} ignored: duplicate id "${r.value.id}"`);
        seen.add(r.value.id);
        out.push(r.value);
      });
      return out;
    },
  };
}

// ── Flat alert rules ─────────────────────────────────────────────────────────

/** The metrics a flat rule can compare, besides the keyed `model:<id>.…` / `repo:<name>.…` forms. */
export const FIXED_ALERT_METRICS = [
  'today.credits',
  'today.cost',
  'month.credits',
  'month.cost',
  'budget.percentOfBudget',
  'budget.percentOfIncluded',
  'forecast.projectedCredits',
  'forecast.projectedCost',
  'velocity.creditsPerHour',
  'window7d.credits',
  'currentBranchCredits',
] as const satisfies readonly FlatAlertMetric[];

const KEYED_METRIC_PATTERN = '^(model|repo):.+\\.(credits|cost)$';
const KEYED_METRIC_RE = new RegExp(KEYED_METRIC_PATTERN);
export const ALERT_OPS = ['>', '>=', '<', '<=', '==', '!='] as const satisfies readonly FlatAlertRule['op'][];
export const ALERT_SEVERITIES = ['info', 'warning', 'critical'] as const satisfies readonly FlatAlertRule['severity'][];
const COOLDOWN_PATTERN = '^\\d+(\\.\\d+)?[mhdw]$';
const COOLDOWN_RE = new RegExp(COOLDOWN_PATTERN);

const isMetric = (v: unknown): v is FlatAlertMetric =>
  typeof v === 'string' && ((FIXED_ALERT_METRICS as readonly string[]).includes(v) || KEYED_METRIC_RE.test(v));
const isCooldown = (v: unknown): v is string => typeof v === 'string' && COOLDOWN_RE.test(v) && parseFloat(v) > 0;
const oneOf = (values: readonly string[]) => (v: unknown): boolean => values.includes(v as string);

/** Field checks for a flat rule: [name, valid?, required?]. The shape of `FlatAlertRule` in domain/contracts.ts. */
const RULE_FIELDS: ReadonlyArray<readonly [string, (v: unknown) => boolean, boolean]> = [
  ['id', isText, true],
  ['metric', isMetric, true],
  ['op', oneOf(ALERT_OPS), true],
  ['value', isNumber, true],
  ['cooldown', isCooldown, true],
  ['severity', oneOf(ALERT_SEVERITIES), true],
  ['notify', (v) => typeof v === 'boolean', false],
  ['restrict', (v) => typeof v === 'boolean', false],
  ['clearBelow', isNumber, false],
];

function ruleItem(raw: unknown): ItemResult<FlatAlertRule> {
  if (!isRecord(raw)) return { error: 'not an object' };
  for (const [field, valid, required] of RULE_FIELDS) {
    const v = raw[field];
    if (v === undefined ? required : !valid(v)) return { error: `"${field}" is ${v === undefined ? 'missing' : 'invalid'}` };
  }
  const r = raw as unknown as FlatAlertRule;
  // Rebuilt from the known fields so stray properties never leak into the config.
  return {
    value: {
      id: r.id.trim(), metric: r.metric, op: r.op, value: r.value, cooldown: r.cooldown, severity: r.severity,
      ...opt('notify', r.notify), ...opt('restrict', r.restrict), ...opt('clearBelow', r.clearBelow),
    },
  };
}

// ── Export targets ───────────────────────────────────────────────────────────

/** A target's stable id: also namespaces its SecretStorage keys and its retry queue file. */
export const TARGET_ID_PATTERN = '^[A-Za-z0-9._-]{1,32}$';
export const TARGET_ID_RE = new RegExp(TARGET_ID_PATTERN);

function targetItem(raw: unknown): ItemResult<ExportTarget> {
  if (!isRecord(raw)) return { error: 'not an object' };
  const { id, name, url } = raw;
  if (typeof id !== 'string' || !TARGET_ID_RE.test(id)) return { error: '"id" must be 1-32 letters, digits, dots, underscores or dashes' };
  if (!isText(name)) return { error: '"name" is missing' };
  if (!isText(url)) return { error: '"url" is missing' };
  return { value: { id, name: name.trim(), url: url.trim() } };
}

/** `base` made into a valid target id that is not in `taken` (`team`, `team-2`, `team-3`…). */
export function uniqueTargetId(base: string, taken: ReadonlySet<string>): string {
  const slug = base.replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 28) || 'target';
  for (let n = 1; ; n++) {
    const id = n === 1 ? slug : `${slug}-${n}`;
    if (!taken.has(id)) return id;
  }
}

const TARGET_ITEMS: JsonSchema = {
  type: 'object',
  required: ['id', 'name', 'url'],
  properties: {
    id: { type: 'string', pattern: TARGET_ID_PATTERN, description: 'Stable id (letters, digits, dot, underscore, dash). Namespaces this target\'s stored credentials: do not change it once credentials are set.' },
    name: { type: 'string', minLength: 1, description: 'Label shown in the Mallard pickers.' },
    url: { type: 'string', minLength: 1, description: 'Endpoint URL.' },
  },
  additionalProperties: false,
};

const RULE_ITEMS: JsonSchema = {
  type: 'object',
  required: ['id', 'metric', 'op', 'value', 'cooldown', 'severity'],
  properties: {
    id: { type: 'string', minLength: 1, description: 'Unique rule id.' },
    metric: {
      type: 'string',
      description: 'What to compare: a fixed metric, or model:<id>.credits|cost / repo:<name>.credits|cost.',
      anyOf: [{ enum: [...FIXED_ALERT_METRICS] }, { pattern: KEYED_METRIC_PATTERN }],
    },
    op: { enum: [...ALERT_OPS], description: 'Comparison operator.' },
    value: { type: 'number', description: 'Threshold the metric is compared against.' },
    cooldown: { type: 'string', pattern: COOLDOWN_PATTERN, description: 'Minimum time between firings: a positive number and m/h/d/w, e.g. "30m", "1.5h", "2d".' },
    severity: { enum: [...ALERT_SEVERITIES], description: 'Notification severity.' },
    notify: { type: 'boolean', description: 'Show a notification when the rule fires.' },
    restrict: { type: 'boolean', description: 'Raise the (notification-only) usage-limit restriction while the rule matches.' },
    clearBelow: { type: 'number', description: 'Lift the restriction once the metric falls below this value, instead of as soon as the rule stops matching.' },
  },
  additionalProperties: false,
};

// ── Branch budgets ───────────────────────────────────────────────────────────

function branchBudgets(o: Common): SettingDef<Record<string, number>> {
  return {
    ...o,
    type: 'object',
    default: {},
    additionalProperties: { type: 'number', minimum: 0, maximum: MAX_AMOUNT },
    sanitize: (raw, ctx) => {
      if (raw === undefined) return {};
      if (!isRecord(raw)) {
        ctx.report('expected an object of branch name to credits; ignoring it');
        return {};
      }
      const out: Record<string, number> = {};
      for (const [branch, cap] of Object.entries(raw)) {
        if (!isNumber(cap) || cap < 0 || branch.trim() === '') ctx.report(`"${branch}" ignored: needs a credit cap of 0 or more`);
        else out[branch] = Math.min(cap, MAX_AMOUNT);
      }
      return out;
    },
  };
}

function connectors(o: Common & { default: readonly string[]; itemEnum: readonly string[] }): SettingDef<string[]> {
  const { itemEnum, default: dflt, ...rest } = o;
  return {
    ...rest,
    type: 'array',
    default: [...dflt],
    items: { type: 'string', enum: [...itemEnum] },
    sanitize: (raw, ctx) => {
      if (raw === undefined) return [...dflt];
      if (!Array.isArray(raw)) {
        ctx.report('expected an array of connector ids; using the default');
        return [...dflt];
      }
      const ok = new Set<string>();
      for (const id of raw) {
        if (itemEnum.includes(id as string)) ok.add(id as string);
        else ctx.report(`unknown connector ${JSON.stringify(id)} ignored`);
      }
      return [...ok];
    },
  };
}

