export type SettingKey = keyof typeof SETTINGS;
/** The sanitised value type of each setting, by key. */
export type SettingValues = { [K in SettingKey]: ReturnType<(typeof SETTINGS)[K]['sanitize']> };

/** Every key with its definition, in table order. */
export const SETTING_ENTRIES = Object.entries(SETTINGS) as Array<[SettingKey, SettingDef<unknown>]>;

/** Settings that are only read at activation (changing them prompts for a reload). */
export const RELOAD_REQUIRED_KEYS: readonly SettingKey[] = SETTING_ENTRIES.filter(([, d]) => d.reload).map(([k]) => k);

/**
 * Read every setting through its sanitiser. `read` returns the raw configured
 * value for a full key (`mallard.x`); `problem` receives each value that was
 * dropped or replaced. Never throws.
 */
export function readSettings(read: (key: SettingKey) => unknown, problem: (message: string) => void): SettingValues {
  const targetIds = new Set<string>();
  const out: Record<string, unknown> = {};
  for (const [key, def] of SETTING_ENTRIES) {
    out[key] = def.sanitize(read(key), { targetIds, report: (p) => problem(`${key}: ${p}`) });
  }
  return out as SettingValues;
}
